"""验证基准恢复身份覆盖影响输出的资源，而非解释器自动生成的缓存。"""

from __future__ import annotations

import importlib
import json
from pathlib import Path
from types import SimpleNamespace

import pytest


def test_source_identity_changes_when_runtime_resource_changes(tmp_path: Path, monkeypatch) -> None:
    """字体或配置资源变化必须让相同 Python 源码的旧基准记录失效。"""
    monkeypatch.syspath_prepend(str(Path(__file__).parent / "benchmarks"))
    benchmark = importlib.import_module("rust_pdf")
    package = tmp_path / "src/docvortex/__init__.py"
    package.parent.mkdir(parents=True)
    package.write_text("", encoding="utf-8")
    resource = package.parent / "resources/font-config.json"
    resource.parent.mkdir()
    resource.write_text('{"font": "first"}', encoding="utf-8")
    before = benchmark.source_identity(package)
    resource.write_text('{"font": "second"}', encoding="utf-8")
    after = benchmark.source_identity(package)
    assert before["source_code_sha256"] != after["source_code_sha256"]


def test_source_identity_ignores_generated_bytecode_and_separately_checked_binary(tmp_path: Path, monkeypatch) -> None:
    """运行生成的字节码不污染源码身份，原生扩展由独立二进制摘要校验。"""
    monkeypatch.syspath_prepend(str(Path(__file__).parent / "benchmarks"))
    benchmark = importlib.import_module("rust_pdf")
    package = tmp_path / "src/docvortex/__init__.py"
    package.parent.mkdir(parents=True)
    package.write_text("", encoding="utf-8")
    before = benchmark.source_identity(package)
    cache = package.parent / "__pycache__"
    cache.mkdir()
    (cache / "__init__.cpython-314.pyc").write_bytes(b"generated bytecode")
    (package.parent / "_native.abi3.so").write_bytes(b"separately validated native binary")
    assert benchmark.source_identity(package) == before


def test_native_worker_preserves_both_outputs_when_repeated_result_changes(tmp_path: Path, monkeypatch) -> None:
    """中途输出不稳定时保存参考和失败轮的完整内容，避免只有摘要而无法裁决。"""
    monkeypatch.syspath_prepend(str(Path(__file__).parent / "benchmarks"))
    benchmark = importlib.import_module("rust_pdf")
    source = tmp_path / "input.pdf"
    source.write_bytes(b"controlled worker input")
    reference = {"model": {"pages": []}, "middle": {}, "assets": {}, "diagnostics": []}
    changed = {**reference, "diagnostics": [{"code": "changed", "message": "可定位差异"}]}
    outputs = iter((reference, changed))

    def replay(payload: bytes):
        """注入跨运行的诊断变化，验证正式 worker 的不稳定结果门禁。"""
        assert payload == source.read_bytes()
        return {"parse": 0.01}, next(outputs)

    monkeypatch.setattr(benchmark, "public_once", replay)
    destination = tmp_path / "output"
    with pytest.raises(AssertionError, match="Non-deterministic output"):
        benchmark.worker(SimpleNamespace(worker=str(source), suite="public", runs=1, output=destination))
    assert json.loads((destination / "output.json").read_text(encoding="utf-8")) == reference
    assert json.loads((destination / "output-run-1-mismatch.json").read_text(encoding="utf-8")) == changed
    progress = json.loads((destination / "progress.json").read_text(encoding="utf-8"))
    assert progress["status"] == "failed" and progress["failed_run"] == 1
